import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { getProject } from '../repo/projects.ts'
import { listNotes } from '../repo/notes.ts'
import { listIdeas } from '../repo/ideas.ts'
import { listTasks } from '../repo/tasks.ts'
import { nowIso } from '../db/database.ts'
import type { ProjectExport, Tag } from '../../shared/types.ts'

const names = (tags: Tag[]): string[] => tags.map((t) => t.name)

export function buildExport(projectId: number): ProjectExport | null {
  const project = getProject(projectId)
  if (!project) return null
  return {
    generatedAt: nowIso(),
    project: {
      id: project.id,
      name: project.name,
      path: project.path,
      description: project.description,
      status: project.status,
      tags: names(project.tags),
      stack: project.stack,
      activity: project.activity
    },
    notes: listNotes(projectId).map((n) => ({
      id: n.id,
      title: n.title,
      body: n.body,
      pinned: n.pinned,
      updatedAt: n.updatedAt,
      tags: names(n.tags)
    })),
    ideas: listIdeas(projectId)
      .filter((i) => i.status !== 'archived')
      .map((i) => ({
        id: i.id,
        title: i.title,
        body: i.body,
        priority: i.priority,
        status: i.status,
        updatedAt: i.updatedAt,
        tags: names(i.tags)
      })),
    tasks: listTasks(projectId)
      .filter((t) => t.status !== 'done')
      .map((t) => ({
        id: t.id,
        title: t.title,
        body: t.body,
        status: t.status,
        priority: t.priority,
        dueDate: t.dueDate,
        updatedAt: t.updatedAt,
        tags: names(t.tags)
      }))
  }
}

const tagSuffix = (tags: string[]): string => (tags.length > 0 ? `  [${tags.join(', ')}]` : '')

// Human- and agent-readable snapshot written to ai-instructions/LAUNCHPAD.md by the CLI.
// Item ids are included on purpose: they're the handle an agent uses to write back.
export function renderExportMarkdown(data: ProjectExport): string {
  const lines: string[] = []
  lines.push(`# ${data.project.name} — Launchpad snapshot`)
  lines.push('')
  lines.push(
    '> Auto-generated by Launchpad — **this file is a read-only mirror**. Editing it changes ' +
      'nothing; Launchpad never reads it back. Refresh with `launchpad pull`.'
  )
  lines.push('>')
  lines.push(
    `> To change anything, write to Launchpad itself — e.g. \`launchpad task add "…"\`, ` +
      `\`launchpad task done ${data.tasks[0]?.id ?? '<id>'}\`, \`launchpad push plan.json\`. ` +
      'Run `launchpad guide` for the full command set.'
  )
  lines.push('')
  lines.push(
    `**Launchpad project #${data.project.id}**  ·  **Status:** ${data.project.status}  ·  ` +
      `**Activity:** ${data.project.activity}  ·  **Generated:** ${data.generatedAt}`
  )
  if (data.project.tags.length > 0) {
    lines.push('')
    lines.push(`**Tags:** ${data.project.tags.join(', ')}`)
  }
  if (data.project.description) {
    lines.push('')
    lines.push(data.project.description)
  }

  lines.push('')
  lines.push('## Open tasks')
  if (data.tasks.length === 0) {
    lines.push('_None._')
  } else {
    for (const t of data.tasks) {
      const mark = t.status === 'doing' ? '~' : ' '
      const due = t.dueDate ? `  (due ${t.dueDate.slice(0, 10)})` : ''
      lines.push(`- [${mark}] \`#${t.id}\` (${t.priority}) ${t.title}${due}${tagSuffix(t.tags)}`)
      if (t.body) {
        for (const line of t.body.split('\n')) lines.push(`      ${line}`)
      }
    }
  }

  lines.push('')
  lines.push('## Ideas')
  if (data.ideas.length === 0) {
    lines.push('_None._')
  } else {
    for (const i of data.ideas) {
      lines.push(
        `- \`#${i.id}\` (${i.priority}) **${i.title}**${i.body ? ` — ${i.body}` : ''}${tagSuffix(i.tags)}`
      )
    }
  }

  lines.push('')
  lines.push('## Notes')
  if (data.notes.length === 0) {
    lines.push('_None._')
  } else {
    for (const n of data.notes) {
      lines.push('')
      lines.push(`### ${n.title || 'Note'} \`#${n.id}\`${n.pinned ? ' 📌' : ''}${tagSuffix(n.tags)}`)
      if (n.body) lines.push(n.body)
    }
  }

  lines.push('')
  return lines.join('\n')
}

// Write the snapshot into the project's ai-instructions/LAUNCHPAD.md (same as `launchpad pull`).
export function writeExportToProject(projectId: number): { path: string } | null {
  const data = buildExport(projectId)
  const project = getProject(projectId)
  if (!data || !project) return null
  const dir = join(project.path, 'ai-instructions')
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true })
  const filePath = join(dir, 'LAUNCHPAD.md')
  writeFileSync(filePath, renderExportMarkdown(data), 'utf-8')
  return { path: filePath }
}
